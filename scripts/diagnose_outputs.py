"""Why does SFT not move Pass@1? Length / truncation / loop diagnostics on finished eval outputs (CPU only).

    ~/.conda/envs/evalenv/bin/python scripts/diagnose_outputs.py                       # every run in eval/outputs/
    ~/.conda/envs/evalenv/bin/python scripts/diagnose_outputs.py base random_s2 full_method_s1_l40s

Reads the per-sample jsonl eval.py wrote (eval/outputs/<run>/**/<bench>/test_*.jsonl; read-only, nothing under
eval/ is written) and reports, per run x benchmark, over all n=8 samples:
  tok_p50 / tok_p90   response length, Qwen2.5 tokenizer
  hit_max             share of samples >= MAX_TOKENS - 64 tokens (cut by eval's max_tokens: never finished)
  no_boxed            share of samples with no extracted answer (eval's own generated_answers is empty)
  loop                share of samples flagged by audit_pool.text_flags' repetition rule
  acc_finished        Pass@1 restricted to samples that did NOT hit max_tokens
  acc_long            Pass@1 of samples longer than 16K tokens that did finish
Writes analysis/eval_diagnostics.csv and analysis/eval_diagnostics.md (generated; do not hand-edit).

Decision this feeds (STATUS, 2026-10-20): if trained models hit max_tokens / loop far more often than base, the
3B model copies R1's length without its ability to finish, and a SHORTER-trace subset is the next run, not
longest_s1.
"""
import argparse
import json
import zlib
from collections import Counter

import numpy as np
import pandas as pd
from transformers import AutoTokenizer

from common import ANALYSIS, BASE_MODEL, BENCHMARKS, EVAL_DIR, md_table

MAX_TOKENS = 32768  # eval_single.sh / eval.py max_tokens


def is_loop(text: str) -> bool:
    """Same repetition rule as audit_pool.text_flags (kept in sync by hand; audit_pool imports its whole pipeline)."""
    tail = text.encode("utf-8", "ignore")[-4000:]
    tail_ratio = len(zlib.compress(tail)) / max(1, len(tail))
    lines = [ln.strip() for ln in text.split("\n") if len(ln.strip()) >= 30]
    max_line_repeat = max(Counter(lines).values()) if lines else 0
    return (len(tail) >= 2000 and tail_ratio < 0.10) or max_line_repeat >= 25


def diagnose(tok, path):
    rows = [json.loads(line) for line in open(path, encoding="utf-8")]
    lens, hit, nob, loop, ok = [], [], [], [], []
    for r in rows:
        resps = r["generated_responses"]
        enc = tok(resps, add_special_tokens=False)["input_ids"]
        lens += [len(e) for e in enc]
        hit += [len(e) >= MAX_TOKENS - 64 for e in enc]
        nob += [not a for a in r["generated_answers"]]
        loop += [is_loop(t) for t in resps]
        ok += [bool(c) for c in r["answers_correctness"]]
    lens, hit, nob, loop, ok = map(np.array, (lens, hit, nob, loop, ok))
    fin_long = (~hit) & (lens > 16384)
    return {"n_q": len(rows), "pass1": ok.mean(),
            "tok_p50": int(np.median(lens)), "tok_p90": int(np.percentile(lens, 90)),
            "hit_max": hit.mean(), "no_boxed": nob.mean(), "loop": loop.mean(),
            "acc_finished": ok[~hit].mean() if (~hit).any() else float("nan"),
            "acc_long": ok[fin_long].mean() if fin_long.any() else float("nan")}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="*", help="dirs under eval/outputs/ (default: all)")
    args = ap.parse_args()
    out_root = EVAL_DIR / "outputs"
    runs = args.runs or sorted(d.name for d in out_root.iterdir() if d.is_dir() and "crashed" not in d.name)
    tok = AutoTokenizer.from_pretrained(BASE_MODEL)
    recs = []
    for run in runs:
        for b in BENCHMARKS:
            files = sorted((out_root / run).glob(f"**/{b}/test_*.jsonl"))
            if not files:
                continue
            print(f"{run} / {b}: {files[-1]}", flush=True)
            recs.append({"run": run, "bench": b, **diagnose(tok, files[-1])})
    if not recs:
        raise SystemExit("no per-sample jsonl found under eval/outputs/")
    df = pd.DataFrame(recs)
    ANALYSIS.mkdir(exist_ok=True)
    df.to_csv(ANALYSIS / "eval_diagnostics.csv", index=False)
    summ = df.groupby("run")[["tok_p50", "tok_p90", "hit_max", "no_boxed", "loop", "pass1", "acc_finished"]].mean()
    md = ["# Eval output diagnostics", "",
          "Generated by `scripts/diagnose_outputs.py`; do not hand-edit. Shares are over all n=8 samples. "
          f"`hit_max` = response >= {MAX_TOKENS - 64} tokens (cut by eval's max_tokens).", "",
          "## Mean over benchmarks", "", md_table(summ.reset_index().round(3)), "",
          "## Per benchmark", "", md_table(df.round(3))]
    (ANALYSIS / "eval_diagnostics.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md[:8]))


if __name__ == "__main__":
    main()
